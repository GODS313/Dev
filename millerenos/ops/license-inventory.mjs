// Writes docs/LICENSES.md from installed production dependencies; --check fails on disallowed licenses.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const ALLOWED =
  /^(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|BlueOak-1\.0\.0|CC0-1\.0|Unlicense|\(MIT OR Apache-2\.0\)|MIT OR Apache-2\.0|Python-2\.0)$/;
const root = path.resolve(import.meta.dirname, '..');
const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const rows = [];
for (const [p, meta] of Object.entries(lock.packages)) {
  if (!p.startsWith('node_modules/') || meta.dev || meta.devOptional || meta.link) continue; // workspaces are our own code
  const name = p.slice(p.lastIndexOf('node_modules/') + 13);
  let license = meta.license;
  const pj = path.join(root, p, 'package.json');
  if (!license && existsSync(pj)) license = JSON.parse(readFileSync(pj, 'utf8')).license;
  rows.push({ name, version: meta.version, license: license ?? 'UNKNOWN' });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const bad = rows.filter((r) => !ALLOWED.test(r.license));
const md =
  `# Third-party license inventory\n\nGenerated by \`npm run licenses\` from package-lock.json (production dependencies only).\n` +
  `Allowed licenses: permissive (MIT, ISC, Apache-2.0, BSD, 0BSD, CC0, BlueOak). Copyleft licenses require review before use.\n\n` +
  `| Package | Version | License |\n|---|---|---|\n` +
  rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n') +
  '\n';
if (process.argv.includes('--check')) {
  if (bad.length) {
    console.error('Disallowed or unknown licenses:\n' + bad.map((r) => `  ${r.name}@${r.version}: ${r.license}`).join('\n'));
    process.exit(1);
  }
  console.log(`license check ok (${rows.length} production packages)`);
} else {
  writeFileSync(path.join(root, 'docs/LICENSES.md'), md);
  console.log(`wrote docs/LICENSES.md (${rows.length} packages, ${bad.length} need review)`);
}
