let current: Locale = 'en';
export const setLocale = (l: Locale) => {
  current = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'fa' ? 'rtl' : 'ltr';
};
export const getLocale = () => current;

export function t(key: Key, vars: Record<string, string | number> = {}) {
  const tpl = (current === 'fa' ? fa : en)[key] ?? en[key];
  return tpl.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export const num = (n: number) => (current === 'fa' ? n.toLocaleString('fa-IR') : String(n));

export function duration(seconds: number) {
  const s = Math.max(0, seconds);
  const m = Math.floor(s / 60);
  const sec = s % 60;
  const text = `${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}`;
  return current === 'fa' ? text.replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]!) : text;
}
